import type { GitaVerse, AIExplanationResponse } from '../types';

export async function askGeminiMentor(
  apiKey: string,
  verse: GitaVerse,
  userQuestion?: string
): Promise<AIExplanationResponse> {
  if (!apiKey || !apiKey.trim()) {
    throw new Error('Please provide a Google Gemini API Key to activate live AI coaching.');
  }

  const prompt = `
You are a wise, compassionate, and deeply practical spiritual mentor and cognitive-behavioral coach specializing in the psychological wisdom of the Bhagavad Gita for modern personal growth and personality development.

The user is contemplating this verse:
Chapter ${verse.chapter}, Verse ${verse.verse} (${verse.chapterTitle})
Sanskrit: ${verse.sanskrit}
Translation: ${verse.englishTranslation}
Theme: ${verse.personalityTheme}

${userQuestion ? `The user asks this specific personal question: "${userQuestion}"` : 'Explain how this verse can directly transform the user\'s character, self-esteem, productivity, and emotional intelligence today.'}

Respond strictly in valid JSON format matching this TypeScript interface:
{
  "customInsight": "A penetrating 2-3 sentence psychological analysis connecting this ancient verse to modern neuroscience or human behavior.",
  "personalCoachAdvice": "Actionable, step-by-step guidance answering how the user can implement this mindset shift starting right now in their career, relationships, or inner dialogue.",
  "morningAffirmation": "A powerful, concise first-person mantra/affirmation (starting with 'I ...') to anchor this trait throughout the day."
}
Only output the raw JSON, no markdown codeblocks, no extra conversational preamble.
`;

  try {
    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey.trim()}`,
      {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          contents: [
            {
              parts: [{ text: prompt }]
            }
          ],
          generationConfig: {
            temperature: 0.7,
            maxOutputTokens: 800,
          }
        })
      }
    );

    if (!response.ok) {
      const errData = await response.json().catch(() => null);
      throw new Error(errData?.error?.message || `API request failed with status ${response.status}`);
    }

    const data = await response.json();
    const candidateText = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!candidateText) {
      throw new Error('No response generated by the model.');
    }

    // Clean any markdown wrapper if present
    const cleanedJson = candidateText.replace(/```json/gi, '').replace(/```/g, '').trim();
    const parsed: AIExplanationResponse = JSON.parse(cleanedJson);
    return parsed;
  } catch (error: any) {
    console.error('Error contacting Gemini API:', error);
    throw new Error(error.message || 'Failed to communicate with AI Mentor.');
  }
}
